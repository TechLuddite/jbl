/**
 * Combined effectiveness of one attacking type against a 1- or 2-type defender.
 * Multiplies, so dual types can reach 4x or 0.25x.
 */
export function typeEffectiveness(attackType, defenderTypes) {
  return defenderTypes.reduce(
    (mult, def) => mult * (TYPE_CHART[attackType]?.[def] ?? 1),
    1
  );
}
